/** Converts the legacy signaling layer's wire-safe English messages into
 * client-localized copy. Unknown errors still receive a localized safe
 * fallback; unknown status text is retained for forward compatibility. */
export function localizeCoopSignalingMessage(language: CoopLanguage, message: string, kind: 'status' | 'error') {
  const exact: Record<string, CoopTextKey> = {
    'Pinging squad frequency…': 'status.pinging',
    'Negotiating direct peer link…': 'status.negotiating',
    'Link verified — syncing tactical mesh…': 'status.linkVerified',
    'Direct peer link established. Finalizing handshake…': 'status.finalizing',
    'Joining match…': 'status.joining',
    'Ready — waiting for the host to deploy.': 'status.readyHostDeploy',
    'Operative connected via direct WebRTC link!': 'status.operativeConnected',
    'Operative connected to squad!': 'status.operativeConnected',
    'Reconnecting squad signal…': 'status.reconnectingSignal',
    'Connection timed out. Squad leader may be unreachable.': 'error.timeout',
    'Failed to establish peer connection with host.': 'error.peerHost',
    'Couldn’t reach the squad. Try another room or code.': 'error.reachSquad',
    'Couldn’t connect to this squad. Try another one.': 'error.connectSquad',
    'Couldn’t join this squad. Try another one.': 'error.joinSquad',
    'Failed to negotiate peer connection.': 'error.negotiate',
    'This squad is full.': 'error.squadFull',
    'This squad is no longer available.': 'error.squadUnavailable',
    'Signal broker is busy. Try again in a moment.': 'error.brokerBusy',
    'Couldn’t reach the squad frequency. Try again.': 'error.frequencyUnavailable',
  };
  const key = exact[message];
  if (key) return coopText(language, key);
  const connecting = message.match(/^Operative (.+) is connecting…$/);
  if (connecting) return coopText(language, 'status.operativeConnecting', { name: connecting[1] });
  const joined = message.match(/^(.+) joined squad\.$/);
  if (joined) return coopText(language, 'status.operativeJoined', { name: joined[1] });
  const joining = message.match(/^(.+) joining…$/);
  if (joining) return coopText(language, 'status.operativeJoining', { name: joining[1] });
  return kind === 'error' ? coopText(language, 'error.joinSquad') : message;
}
