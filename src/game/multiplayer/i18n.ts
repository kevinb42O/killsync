const catalogs: Record<CoopLanguage, Record<CoopTextKey, string>> = { en, ru };

export function normalizeCoopLanguage(value: unknown): CoopLanguage {
  return value === 'ru' ? 'ru' : 'en';
}

export function readCoopLanguage(): CoopLanguage {
  try { return normalizeCoopLanguage(localStorage.getItem(COOP_LANGUAGE_STORAGE_KEY)); }
  catch { return 'en'; }
}

export function writeCoopLanguage(language: CoopLanguage) {
  try { localStorage.setItem(COOP_LANGUAGE_STORAGE_KEY, language); }
  catch { /* A blocked storage API must not block multiplayer. */ }
}

export function coopText(language: CoopLanguage, key: CoopTextKey, params: CoopTextParams = {}): string {
  const template = catalogs[language]?.[key] || (en as Record<string, string>)[key] || String(key);
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function isCoopTextKey(value: unknown): value is CoopTextKey {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(en, value);
}

